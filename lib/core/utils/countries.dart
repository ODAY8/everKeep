import 'package:phone_numbers_parser/phone_numbers_parser.dart';

/// A country/territory the phone-number field lets the user pick as the
/// country code for their number.
class Country {
  final IsoCode isoCode;
  final String name;

  const Country(this.isoCode, this.name);

  /// The dial code that precedes the national number (e.g. "1" for the US),
  /// from `phone_numbers_parser`'s own numbering-plan data — never hand-typed,
  /// so it can't drift out of sync with what actually validates.
  String get dialCode => PhoneNumber(isoCode: isoCode, nsn: '').countryCode;

  /// The flag, built from Unicode regional indicator symbols rather than an
  /// image asset, so it needs no bundled artwork and is always correct.
  String get flag {
    const base = 0x1F1E6;
    const aCode = 0x41; // 'A'
    return String.fromCharCodes(
      isoCode.name.codeUnits.map((c) => base + (c - aCode)),
    );
  }
}

