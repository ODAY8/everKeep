/// The best default country to preselect: the device's own region, falling
/// back to the US if that isn't one of [kCountries] (e.g. a region code the
/// phone-number library doesn't cover).
Country defaultCountry(String? deviceCountryCode) {
  final upper = deviceCountryCode?.toUpperCase();
  for (final country in kCountries) {
    if (country.isoCode.name == upper) return country;
  }
  return kCountries.firstWhere((c) => c.isoCode == IsoCode.US);
}
